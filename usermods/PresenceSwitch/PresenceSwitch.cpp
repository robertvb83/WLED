void PresenceSwitchUsermod::addIpsFromString(const String &list, std::vector<uint32_t> &out)
{
    int start = 0;
    while (start < (int)list.length())
    {
        while (start < (int)list.length() && (list[start] == ',' || list[start] == ' ' || list[start] == ';'))
            start++;
        int end = start;
        while (end < (int)list.length() && list[end] != ',' && list[end] != ' ' && list[end] != ';')
            end++;
        if (end > start)
        {
            IPAddress ip;
            if (ip.fromString(list.substring(start, end)))
            {
                uint32_t k = ipToKey(ip);
                if (std::find(out.begin(), out.end(), k) == out.end())
                    out.push_back(k);
            }
        }
        start = end;
    }
}

void PresenceSwitchUsermod::applySwitch(bool on)
{
    if (on)
    {
        if (!switchedOffByMod)
            return; // only turn back on if we were the ones who turned it off
        bri = restoreBri;
        switchedOffByMod = false;
        // only reset segments actually running Scrolling Text (stuck font cache after a long off period);
        // a full strip.restartRuntime() would also reset unrelated segments (e.g. an active playlist preset)
        for (size_t s = 0; s < strip.getSegmentsNum(); s++) {
            Segment &seg = strip.getSegment(s);
            if (seg.mode == FX_MODE_2DSCROLLTEXT) seg.markForReset();
        }
    }
    else
    {
        if (bri == 0)
            return;
        restoreBri = bri;
        bri = 0;
        switchedOffByMod = true;
    }
    stateUpdated(CALL_MODE_BUTTON);
}

