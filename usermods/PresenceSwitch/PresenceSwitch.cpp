void PresenceSwitchUsermod::startPing(const IPAddress &ip)
{
    pingGotReply = false;
    pingStarted = millis();
#ifdef ARDUINO_ARCH_ESP32
    if (pingHandle)
    {
        esp_ping_delete_session(pingHandle);
        pingHandle = nullptr;
    }

    ip_addr_t target;
    memset(&target, 0, sizeof(target));
    IP4_ADDR(ip_2_ip4(&target), ip[0], ip[1], ip[2], ip[3]);
    target.type = IPADDR_TYPE_V4;

    esp_ping_config_t config = ESP_PING_DEFAULT_CONFIG();
    config.target_addr = target;
    config.count = 1;
    config.timeout_ms = PRESENCE_PING_TIMEOUT_MS;
    config.interval_ms = 0;

    esp_ping_callbacks_t cbs = {};
    cbs.cb_args = this;
    cbs.on_ping_success = onPingSuccessCb;
    cbs.on_ping_timeout = nullptr;
    cbs.on_ping_end = onPingEndCb;

    pingBusy = (esp_ping_new_session(&config, &cbs, &pingHandle) == ESP_OK);
    if (pingBusy)
        esp_ping_start(pingHandle);
#else
    (void)ip;
    pingBusy = false; // ESP8266: ping engine not implemented, always reports "not found"
#endif
}

void PresenceSwitchUsermod::finishQueue()
{
    mode = Mode::IDLE;
    queue.clear();
#ifdef ARDUINO_ARCH_ESP32
    if (pingHandle)
    {
        esp_ping_delete_session(pingHandle);
        pingHandle = nullptr;
    }
#endif
}

void PresenceSwitchUsermod::advanceQueue()
{
    bool success = pingGotReply;

    if (mode == Mode::PRESENCE)
    {
        size_t watchedIndex = queueIndex;
        if (success)
        {
            watchedPresent[watchedIndex] = true;
            watchedSeenAt[watchedIndex] = millis();
            anyPresent = true;
            lastSeenTime = millis();
        }
        else if (presenceRetriesLeft > 0)
        {
            // phones/tablets in power-save mode can be slow to answer; retry before giving up on this device
            presenceRetriesLeft--;
            startPing(keyToIp(queue[queueIndex]));
            return;
        }
        else
        {
            watchedPresent[watchedIndex] = false;
        }
    }

    queueIndex++;
    if (queueIndex >= queue.size())
    {
        finishQueue();
        return;
    }
    presenceRetriesLeft = PRESENCE_PING_RETRIES;
    startPing(keyToIp(queue[queueIndex]));
}

void PresenceSwitchUsermod::beginPresenceRound()
{
    if (mode != Mode::IDLE || !WLED_CONNECTED)
        return;
    if (watchedIPs.empty())
    {
        anyPresent = false;
        return;
    }

    queue = watchedIPs;
    queueIndex = 0;
    anyPresent = false;
    presenceRetriesLeft = PRESENCE_PING_RETRIES;
    mode = Mode::PRESENCE;
    startPing(keyToIp(queue[0]));
}

void PresenceSwitchUsermod::loop()
{
    if (!initDone || !enabled)
        return;
    unsigned long now = millis();

    if (mode != Mode::IDLE)
    {
        if (pingBusy)
        {
            // safety net in case the underlying callback never fires
            if (now - pingStarted > (unsigned long)PRESENCE_PING_TIMEOUT_MS + 500)
            {
                pingBusy = false;
                pingGotReply = false;
            }
            else
            {
                return;
            }
        }
        advanceQueue();
    }

    if (!WLED_CONNECTED)
        return;

    if (now - lastFullCheck >= (unsigned long)checkIntervalSec * 1000UL)
    {
        lastFullCheck = now;
        beginPresenceRound();
    }

    if (offDelayMin > 0 && !watchedIPs.empty())
    {
        if (!anyPresent && (now - lastSeenTime > (unsigned long)offDelayMin * 60000UL))
        {
            applySwitch(false);
        }
        else if (anyPresent && switchedOffByMod)
        {
            applySwitch(true);
        }
    }
}

